// Canonical palette: edit lib/brand/colors.json, then run this script.
import { readFileSync, writeFileSync } from 'node:fs';
const colors = JSON.parse(readFileSync(new URL('../lib/brand/colors.json', import.meta.url), 'utf8'));
const path = new URL('../app/brand-colors.css', import.meta.url);
const tokens = {
  'brand-50': colors.surface, 'brand-100': colors.selected, 'brand-200': colors.border,
  'brand-300': '#B8CAE3', 'brand-400': '#8BA8CE', 'brand-500': colors.secondary,
  'brand-600': colors.secondary, 'brand-700': colors.primary, 'brand-800': colors.primaryHover,
  'brand-900': '#14284D', 'brand-950': '#0D1C36',
  'ink-50': colors.surface, 'ink-100': colors.selected, 'ink-200': colors.border,
  'ink-500': colors.muted, 'ink-600': colors.muted, 'ink-700': colors.muted,
  'ink-800': colors.text, 'ink-900': colors.text,
  ...Object.fromEntries(['50','100','300','400','500','600','700'].map((shade) => [`accent-${shade}`, Number(shade) < 300 ? colors.selected : Number(shade) < 600 ? colors.secondary : colors.primary])),
  'success': colors.success, 'success-surface': colors.successSurface,
  'warning': colors.warning, 'warning-surface': colors.warningSurface,
  'error': colors.error, 'error-surface': colors.errorSurface,
};
// Preserve semantic classes already used across public pages and supplier forms.
for (const family of ['emerald', 'green']) {
  for (const shade of ['50','100']) tokens[`${family}-${shade}`] = colors.successSurface;
  for (const shade of ['600','700','800','900']) tokens[`${family}-${shade}`] = colors.success;
}
for (const family of ['amber', 'yellow']) {
  for (const shade of ['50','100']) tokens[`${family}-${shade}`] = colors.warningSurface;
  for (const shade of ['700','800','900','950']) tokens[`${family}-${shade}`] = colors.warning;
}
for (const family of ['red', 'rose']) {
  for (const shade of ['50','100']) tokens[`${family}-${shade}`] = colors.errorSurface;
  for (const shade of ['600','700','800','900']) tokens[`${family}-${shade}`] = colors.error;
}
const css = '/* Generated by scripts/sync-brand-colors.mjs. Do not edit directly. */\n@theme {\n' + Object.entries(tokens).map(([key,value]) => `  --color-${key}: ${value};`).join('\n') + '\n}\n';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== css) throw Error('Run node scripts/sync-brand-colors.mjs');
} else writeFileSync(path, css);
